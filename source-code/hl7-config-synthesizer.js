/**
 * HL7Forge Pro - Healthcare Gateway Firewall & Threat Detection Synthesizer
 * Generates Linux nftables rules, Suricata HL7 L7 signatures, and TLS 1.3 PKI scripts.
 */

(function (root, factory) {
  if (typeof define === 'function' && define.amd) {
    define([], factory);
  } else if (typeof module === 'object' && module.exports) {
    module.exports = factory();
  } else {
    root.HL7ConfigSynthesizer = factory();
  }
}(typeof self !== 'undefined' ? self : this, function () {
  'use strict';

  /**
   * Generates Linux nftables firewall rules for healthcare integration gateways
   */
  function generateNftablesRules(config) {
    config = config || {};
    var mllpPort = config.mllpPort || 2575;
    var fhirPort = config.fhirPort || 8443;
    var allowPlaintext = !!config.allowPlaintext;
    var clinicalIface = config.clinicalInterface || 'eth0.100';
    var guestIface = config.guestInterface || 'eth1.500';
    var maxConnRate = config.maxConnectionRate || '20/second';
    var authorizedEhrIps = config.authorizedEhrIps || [
      '192.168.1.40',  // Epic Core Server
      '192.168.1.41',  // Cerner Millennium
      '192.168.1.42',  // LIS Lab System
      '192.168.1.45'   // State Health Information Exchange (HIE)
    ];

    var ipList = authorizedEhrIps.join(', ');

    return [
      '#!/usr/sbin/nft -f',
      '# HL7Forge Pro - Healthcare Integration Gateway Ingress & HIPAA Rules',
      '# Standard: HIPAA Security Rule 45 CFR 164.312 / NIST SP 800-41',
      '',
      'flush ruleset',
      '',
      'table ip healthcare_gw {',
      '    # Whitelist of authorized EHR/LIS servers and HIE endpoints',
      '    set authorized_endpoints {',
      '        type ipv4_addr',
      '        elements = { ' + ipList + ' }',
      '    }',
      '',
      '    chain input {',
      '        type filter hook input priority filter; policy drop;',
      '',
      '        # Loopback and established connections',
      '        iif "lo" accept',
      '        ct state established,related accept',
      '        ct state invalid drop',
      '',
      '        # 1. Rate-limit MLLP and FHIR connection bursts to mitigate DoS',
      '        iifname "' + clinicalIface + '" tcp dport { ' + mllpPort + ', ' + fhirPort + ' } ct state new limit rate ' + maxConnRate + ' burst 15 packets accept',
      '        iifname "' + clinicalIface + '" tcp dport { ' + mllpPort + ', ' + fhirPort + ' } ct state new log prefix "HL7_BURST_FLOOD_DROP: " drop',
      '',
      '        # 2. Secure FHIR HTTPS (Port ' + fhirPort + ') - Authorized endpoints only',
      '        iifname "' + clinicalIface + '" ip saddr @authorized_endpoints tcp dport ' + fhirPort + ' ct state new accept',
      '',
      allowPlaintext ?
      '        # WARNING: Plaintext MLLP (Port ' + mllpPort + ') enabled for legacy interfaces\n' +
      '        iifname "' + clinicalIface + '" ip saddr @authorized_endpoints tcp dport ' + mllpPort + ' ct state new accept' :
      '        # Strictly block unencrypted MLLP on Port ' + mllpPort + ' to satisfy HIPAA mandates\n' +
      '        iifname "' + clinicalIface + '" tcp dport ' + mllpPort + ' log prefix "HL7_PLAINTEXT_BLOCKED: " drop',
      '',
      '        # Default drop counter',
      '        counter log prefix "HEALTHCARE_GW_REJECT: " drop',
      '    }',
      '',
      '    chain forward {',
      '        type filter hook forward priority filter; policy drop;',
      '',
      '        # Inhibit Guest/Admin VLAN (' + guestIface + ') from bridging to Clinical EHR VLAN (' + clinicalIface + ')',
      '        iifname "' + guestIface + '" oifname "' + clinicalIface + '" log prefix "EHR_VLAN_BREACH_ALERT: " drop',
      '    }',
      '}'
    ].join('\n');
  }

  /**
   * Generates Suricata Layer 7 HL7 threat detection signatures
   */
  function generateSuricataRules(config) {
    return [
      '# Suricata L7 HL7 v2 & FHIR Threat Detection Signatures',
      '# Generated by HL7Forge Pro - HIPAA & IHE ATNA Compliance Engine',
      '',
      '# 1. Alert on unencrypted plaintext MLLP transmission (Port 2575)',
      'alert tcp any any -> any 2575 (msg:"HL7-IDS: Insecure Plaintext MLLP Clinical Stream (HIPAA Warning)"; flow:to_server; content:"|0B|MSH|^~\\&|",offset:0,depth:10; classtype:policy-violation; priority:2; sid:90014401; rev:1;)',
      '',
      '# 2. Alert on High-Frequency ADT Patient Registration Flood (Potential Data Tampering)',
      'alert tcp any any -> any [2575,8443] (msg:"HL7-IDS: High-Frequency Patient Admission/Registration Storm"; flow:to_server; content:"ADT^A",distance:0; threshold:type both, track by_src, count 25, seconds 5; classtype:attempted-dos; priority:1; sid:90014402; rev:1;)',
      '',
      '# 3. Detect Malformed MSH Header Segment (Missing Separators or Fuzzing Attempt)',
      'alert tcp any any -> any 2575 (msg:"HL7-IDS: Malformed MSH Header Segment Detected"; flow:to_server; content:"|0B|MSH",offset:0,depth:4; byte_test:1,!=,0x7C,4; classtype:protocol-command-decode; priority:2; sid:90014403; rev:1;)',
      '',
      '# 4. Critical Alert: Script Injection or SQL Pattern in OBX Clinical Observation Value',
      'alert tcp any any -> any [2575,8443] (msg:"HL7-IDS: CRITICAL - Potential Code Injection in Clinical Result (OBX-5)"; flow:to_server; pcre:"/OBX\|.*\|.*\|.*\|.*\|<script|union.*select/i"; classtype:bad-unknown; priority:1; sid:90014404; rev:1;)',
      '',
      '# 5. Alert on MLLP Replay Attack (Duplicate Message Control ID within Window)',
      'alert tcp any any -> any 2575 (msg:"HL7-IDS: Duplicate Message Control ID Detected in MSH-10"; flow:to_server; threshold:type both, track by_src, count 5, seconds 10; classtype:suspicious-traffic; priority:2; sid:90014405; rev:1;)'
    ].join('\n');
  }

  /**
   * Generates TLS 1.3 mTLS certificate provisioning script for healthcare HIEs
   */
  function generateTlsProvisioningScript(config) {
    config = config || {};
    var hospitalName = config.hospitalName || 'MemorialHealthcare';
    var gwHostname = config.gatewayHostname || 'hie-gw.hospital.internal';

    return [
      '#!/bin/bash',
      '# Healthcare HIE / SMART on FHIR TLS 1.3 Mutual PKI Generator',
      'set -euo pipefail',
      '',
      'echo "=== Generating Healthcare HIE & FHIR TLS 1.3 Certificates ==="',
      'mkdir -p certs && cd certs',
      '',
      '# 1. Hospital Health Information Exchange Root CA',
      'openssl ecparam -name prime256v1 -genkey -noout -out hie_root_ca.key',
      'openssl req -new -x509 -sha256 -days 3650 -key hie_root_ca.key -out hie_root_ca.crt \\',
      '    -subj "/C=US/O=' + hospitalName + '/OU=Clinical Interoperability/CN=' + hospitalName + ' HIE Root CA"',
      '',
      '# 2. Healthcare Integration Gateway Server Certificate',
      'openssl ecparam -name prime256v1 -genkey -noout -out hie_gateway.key',
      'openssl req -new -key hie_gateway.key -out hie_gateway.csr \\',
      '    -subj "/C=US/O=' + hospitalName + '/OU=Integration Gateway/CN=' + gwHostname + '"',
      '',
      'cat <<EOF > v3_gw.ext',
      'authorityKeyIdentifier=keyid,issuer',
      'basicConstraints=CA:FALSE',
      'keyUsage = digitalSignature, keyEncipherment',
      'extendedKeyUsage = serverAuth',
      'subjectAltName = @alt_names',
      '[alt_names]',
      'DNS.1 = ' + gwHostname + '',
      'IP.1 = 192.168.1.100',
      'EOF',
      '',
      'openssl x509 -req -in hie_gateway.csr -CA hie_root_ca.crt -CAkey hie_root_ca.key \\',
      '    -CAcreateserial -out hie_gateway.crt -days 730 -sha256 -extfile v3_gw.ext',
      '',
      '# 3. EHR Client Certificate (Epic / Cerner)',
      'openssl ecparam -name prime256v1 -genkey -noout -out ehr_client.key',
      'openssl req -new -key ehr_client.key -out ehr_client.csr \\',
      '    -subj "/C=US/O=' + hospitalName + '/OU=EHR Clinical Core/CN=EPIC-CORE-01"',
      '',
      'cat <<EOF > v3_client.ext',
      'authorityKeyIdentifier=keyid,issuer',
      'basicConstraints=CA:FALSE',
      'keyUsage = digitalSignature, keyEncipherment',
      'extendedKeyUsage = clientAuth',
      'EOF',
      '',
      'openssl x509 -req -in ehr_client.csr -CA hie_root_ca.crt -CAkey hie_root_ca.key \\',
      '    -CAcreateserial -out ehr_client.crt -days 365 -sha256 -extfile v3_client.ext',
      '',
      'echo "=== Healthcare TLS 1.3 certificates successfully generated in ./certs ==="'
    ].join('\n');
  }

  return {
    generateNftablesRules: generateNftablesRules,
    generateSuricataRules: generateSuricataRules,
    generateTlsProvisioningScript: generateTlsProvisioningScript
  };
}));
